const approved = JSON.parse(fs.readFileSync(approvedPath, 'utf8'));
const architect = JSON.parse(fs.readFileSync(architectPath, 'utf8'));

let added = 0;
let updated = 0;

for (const q of approved.questions.filter((x) => x.category === '系统设计')) {
  const skill = q.skill?.trim();
  if (!skill) continue;

  const expansion = ARCHITECT_EXPANSIONS[skill];
  const baseRef = String(q.referenceAnswer || '').trim();
  if (!baseRef) continue;

  let referenceAnswer = baseRef;
  if (expansion) {
    const sig = expansion.slice(0, 20);
    if (!referenceAnswer.includes(sig)) {
      referenceAnswer = /[。！？]$/.test(referenceAnswer)
        ? `${referenceAnswer}${expansion}`
        : `${referenceAnswer}。${expansion}`;
    }
  }

  const excellentAnswer = String(q.excellentAnswer || '').trim()
    || `我会先明确目标和约束，再展开${skill}的核心机制、关键取舍和验证方式。`;

  if (!architect[skill]) {
    architect[skill] = { referenceAnswer, excellentAnswer };
    added += 1;
  } else if (referenceAnswer.length > (architect[skill].referenceAnswer || '').length + 20) {
    architect[skill] = { referenceAnswer, excellentAnswer };
    updated += 1;
  }
}

fs.writeFileSync(architectPath, `${JSON.stringify(architect, null, 2)}\n`, 'utf8');
console.log(JSON.stringify({ added, updated, total: Object.keys(architect).length }, null, 2));
